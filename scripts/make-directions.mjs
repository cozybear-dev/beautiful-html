// Writes src/css/directions/<name>.css from src/directions.mjs:
// font faces, colour tokens generated from the accent, then the direction's
// layout rules. Dev-only.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { brandTokens, tokensToCss } from '../skills/beautiful-html/tools/brand.mjs';
import { DIRECTION_DEFS } from '../src/directions.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function faces([family, dir]) {
  const meta = JSON.parse(readFileSync(join(root, 'src', 'fonts', dir, 'faces.json'), 'utf8'));
  return meta.faces.map(f => `@font-face { font-family: "${family}"; src: url(font:${dir}/${f.file}) format("woff2"); font-weight: ${f.weight}; font-style: ${f.style}; font-display: block; }`).join('\n');
}
const stack = ([family, , fallback]) => `"${family}", ${fallback}`;

// The stylesheet for one direction. `def`: { accent, ground, text, display?, data? },
// each face given as [family, folder under src/fonts, fallback stack].
export function directionCss(name, def) {
  const text = def.text, display = def.display || def.text, data = def.data || def.text;
  const used = [text, display, data].filter((f, i, all) => all.findIndex(o => o[1] === f[1]) === i);
  const sets = brandTokens({ accent: def.accent, ground: def.ground });
  const structure = readFileSync(join(root, 'src', 'css', 'directions', 'structure', `${name}.css`), 'utf8');
  return `/* Generated by scripts/make-directions.mjs from src/directions.mjs. Do not edit by hand. */
${used.map(faces).join('\n')}

:root {
  --bh-font-text: ${stack(text)};
  --bh-font-display: ${stack(display)};
  --bh-font-data: ${stack(data)};
}

${tokensToCss(sets)}
${structure}`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const [name, def] of Object.entries(DIRECTION_DEFS)) {
    writeFileSync(join(root, 'src', 'css', 'directions', `${name}.css`), directionCss(name, def));
    console.log(`wrote src/css/directions/${name}.css`);
  }
}
